package railway;

public class User {
		
		    String userId;
		    String name;
		    int age;
		    String mobile;
		    String email;
		    String username;
		    String password;
		    int passengerId;

		    User(String userId, String name, int age, String mobile,
		         String email, String username, String password, int passengerId) {

		        this.userId = userId;
		        this.name = name;
		        this.age = age;
		        this.mobile = mobile;
		        this.email = email;
		        this.username = username;
		        this.password = password;
		        this.passengerId = passengerId;
		    }
		}


